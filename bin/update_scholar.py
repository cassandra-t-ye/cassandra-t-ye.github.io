#!/usr/bin/env python3
"""Pull the paper list from Google Scholar into _data/scholar.yml.

Run from the repo root:  python3 bin/update_scholar.py
A GitHub Action also runs this weekly (.github/workflows/update-scholar.yml).
If Scholar blocks the request, the existing file is left untouched.
"""
import html
import json
import re
import sys
import urllib.request
from datetime import date

USER_ID = "vEYl-MUAAAAJ"
OUT = "_data/scholar.yml"
BASE = "https://scholar.google.com"
UA = ("Mozilla/5.0 (Macintosh; Intel Mac OS X 14_0) AppleWebKit/537.36 "
      "(KHTML, like Gecko) Chrome/130 Safari/537.36")


def text(fragment):
    return html.unescape(re.sub(r"<.*?>", "", fragment)).replace("\xa0", " ").strip()


def fetch(start):
    url = f"{BASE}/citations?user={USER_ID}&hl=en&cstart={start}&pagesize=100&sortby=pubdate"
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=30) as resp:
        return resp.read().decode("utf-8", "replace")


def parse(page):
    papers = []
    for row in re.findall(r'<tr class="gsc_a_tr">(.*?)</tr>', page, re.S):
        link = re.search(r'<a href="([^"]+)" class="gsc_a_at">(.*?)</a>', row, re.S)
        if not link:
            continue
        gray = re.findall(r'<div class="gs_gray">(.*?)</div>', row, re.S)
        venue = re.sub(r",\s*\d{4}\s*$", "", text(gray[1])) if len(gray) > 1 else ""
        year = re.search(r'gsc_a_h gsc_a_hc gs_ibl">(\d*)<', row)
        cites = re.search(r'class="gsc_a_ac gs_ibl">(\d*)<', row)
        papers.append({
            "title": text(link.group(2)),
            "url": BASE + html.unescape(link.group(1)),
            "authors": text(gray[0]) if gray else "",
            "venue": venue,
            "year": int(year.group(1)) if year and year.group(1) else None,
            "citations": int(cites.group(1)) if cites and cites.group(1) else 0,
        })
    return papers


def main():
    papers, start = [], 0
    while True:
        try:
            page = fetch(start)
        except Exception as err:
            sys.exit(f"Could not reach Google Scholar ({err}); keeping existing {OUT}.")
        batch = parse(page)
        if not batch:
            break
        papers += batch
        if len(batch) < 100:
            break
        start += 100

    if not papers:
        sys.exit(f"No papers found (Scholar may be blocking requests); keeping existing {OUT}.")

    papers.sort(key=lambda p: (p["year"] or 0), reverse=True)
    lines = [f"# Generated by bin/update_scholar.py on {date.today()}. Do not edit by hand.",
             "papers:"]
    for p in papers:
        lines.append(f"  - title: {json.dumps(p['title'], ensure_ascii=False)}")
        for key in ("url", "authors", "venue"):
            lines.append(f"    {key}: {json.dumps(p[key], ensure_ascii=False)}")
        lines.append(f"    year: {p['year'] if p['year'] else 'null'}")
        lines.append(f"    citations: {p['citations']}")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Wrote {len(papers)} papers to {OUT}")


if __name__ == "__main__":
    main()
